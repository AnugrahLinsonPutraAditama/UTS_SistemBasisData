     AirplaneID             INTEGER  NOT NULL , 
     DepAirport             VARCHAR (50)  NOT NULL , 
     DepTime                TIMESTAMP  NOT NULL , 
     ArrAirport             VARCHAR (50)  NOT NULL , 
     ArrTime                TIMESTAMP  NOT NULL 
    ) 
;
 
ALTER TABLE LegInstance 
