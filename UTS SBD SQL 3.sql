ALTER TABLE CanLand 
    ADD CONSTRAINT CanLand_PK PRIMARY KEY ( typeName, AirportCode ) ;
 
CREATE TABLE Fare 
    ( 
     FlightNumber        VARCHAR (50)  NOT NULL , 
     FareCode            VARCHAR (50)  NOT NULL , 
     Amount              NUMERIC  NOT NULL , 
     Restrictions        VARCHAR (50)  NOT NULL 
    ) 
;
 
ALTER TABLE Fare 
    ADD CONSTRAINT Fare_PK PRIMARY KEY ( FlightNumber, FareCode ) ;
 
CREATE TABLE Flight 
    ( 
     FlightNumber VARCHAR (50)  NOT NULL , 
     Airline      VARCHAR (50)  NOT NULL , 
     Weekdays     VARCHAR (50)  NOT NULL 
    ) 
;
 
ALTER TABLE Flight 
    ADD CONSTRAINT Flight_PK PRIMARY KEY ( FlightNumber ) ;
 
CREATE TABLE FlightLeg 
