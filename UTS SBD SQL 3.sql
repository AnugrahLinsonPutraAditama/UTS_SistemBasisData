CREATE TABLE AirPlane 
    ( 
     AirplaneID                   INTEGER  NOT NULL , 
     TotalSeats                   INTEGER  NOT NULL , 
     TypeName                     VARCHAR (50)  NOT NULL , 
     AirplaneType_AirplaneType_ID INTEGER  NOT NULL 
    ) 
;
 
ALTER TABLE AirPlane 
    ADD CONSTRAINT AirPlane_PK PRIMARY KEY ( AirplaneID ) ;
 
CREATE TABLE AirplaneType 
    ( 
     MaxSeats        INTEGER  NOT NULL , 
     Company         VARCHAR (50)  NOT NULL , 
     AirplaneType_ID INTEGER  GENERATED BY DEFAULT AS IDENTITY NOT NULL 
    ) 
;
 
ALTER TABLE AirplaneType 
    ADD CONSTRAINT AirplaneType_PK PRIMARY KEY ( AirplaneType_ID ) ;
 
CREATE TABLE AirPort 
    ( 
     AirportCode VARCHAR (50)  NOT NULL , 
     Name        VARCHAR (50)  NOT NULL , 
     City        VARCHAR (50) , 
     State       VARCHAR (50) 
    ) 
;
 
ALTER TABLE AirPort 
    ADD CONSTRAINT AirPort_PK PRIMARY KEY ( AirportCode ) ;
 
CREATE TABLE CanLand 
    ( 
     typeName                     VARCHAR (50)  NOT NULL , 
     AirportCode                  VARCHAR (50)  NOT NULL , 
     AirplaneType_AirplaneType_ID INTEGER  NOT NULL 
    ) 
